CREATE TABLE refuges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(200) NOT NULL,
    slug VARCHAR(80) NOT NULL UNIQUE,
    zone VARCHAR(40) NOT NULL
);

CREATE TABLE disponibilites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refuge_id BIGINT NOT NULL REFERENCES refuges (id),
    "date" DATE NOT NULL,
    type_hebergement VARCHAR(20) NOT NULL,
    statut VARCHAR(20) NOT NULL,
    niveau_brut VARCHAR(20) NOT NULL,
    derniere_verification TIMESTAMPTZ NOT NULL,
    CONSTRAINT disponibilites_refuge_date_type_uk UNIQUE (refuge_id, "date", type_hebergement)
);

CREATE TABLE abonnements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    refuge_id BIGINT NOT NULL REFERENCES refuges (id),
    type_hebergement VARCHAR(20) NOT NULL,
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL,
    cree_le TIMESTAMPTZ NOT NULL,
    CONSTRAINT abonnements_dates_ok CHECK (date_fin >= date_debut)
);

CREATE INDEX abonnements_refuge_type_idx ON abonnements (refuge_id, type_hebergement);
CREATE INDEX abonnements_date_fin_idx ON abonnements (date_fin);

CREATE TABLE notifications_envoyees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    abonnement_id BIGINT NOT NULL REFERENCES abonnements (id),
    disponibilite_id BIGINT NOT NULL REFERENCES disponibilites (id),
    envoye_le TIMESTAMPTZ NOT NULL,
    CONSTRAINT notifications_abonnement_dispo_uk UNIQUE (abonnement_id, disponibilite_id)
);

